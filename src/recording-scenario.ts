export const sceneStarts = recordingScenes.map((_, index) => recordingScenes.slice(0, index).reduce((total, scene) => total + scene.duration, 0));
export const recordingDuration = recordingScenes.reduce((total, scene) => total + scene.duration, 0);
export function recordingSceneAt(seconds: number) {
  return Math.max(0, sceneStarts.findLastIndex(start => seconds >= start));
}
export function recordingTime(seconds: number) {
  const value = Math.max(0, Math.floor(seconds));
  return `${String(Math.floor(value / 60)).padStart(2, '0')}:${String(value % 60).padStart(2, '0')}`;
}
